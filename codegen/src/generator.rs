//! Converts a [`QuantityDef`] into a complete Rust source file as a `String`,
//! and derives cross-type arithmetic from dimensional analysis.

use std::collections::BTreeSet;

use heck::ToSnakeCase;

use crate::parser::QuantityDef;

// Convenience: append a formatted line (+ newline) to `out`.
// Always routes through `format!` so `{{`/`}}` in literals become `{`/`}` in the output.
macro_rules! w {
    ($out:expr) => { $out.push('\n'); };
    ($out:expr, $($arg:tt)+) => {
        $out.push_str(&format!($($arg)+));
        $out.push('\n');
    };
}

/// Generates a complete `.rs` source file for `qty` and returns it as a `String`.
pub fn generate(qty: &QuantityDef) -> String {
    let mut out = String::with_capacity(64 * 1024);

    emit_header(qty, &mut out);
    emit_enum(qty, &mut out);
    emit_enum_impl(qty, &mut out);
    emit_struct_impl(qty, &mut out);
    emit_arithmetic(qty, &mut out);
    emit_display(qty, &mut out);
    emit_from_str(qty, &mut out);
    out
}

// ── File header & struct definition ──────────────────────────────────────────

fn emit_header(qty: &QuantityDef, out: &mut String) {
    w!(
        out,
        "// Code generated by `cargo run -p codegen` \u{2014} DO NOT EDIT"
    );
    w!(out, "// Source: data/quantities/{}.json", qty.name);
    w!(out);
    w!(out, "#![allow(");
    w!(out, "    unused_parens,");
    w!(out, "    clippy::excessive_precision,");
    w!(out, "    clippy::unreadable_literal,");
    w!(out, "    clippy::too_many_lines");
    w!(out, ")]");
    w!(out);
    w!(out, "use std::fmt;");
    w!(out, "use std::str::FromStr;");
    w!(out, "use std::ops::{{Add, Sub, Mul, Div, Neg}};");
    w!(out, "use crate::Num;");
    w!(out);

    let doc = escape_doc(&qty.doc);
    w!(out, "/// {}", doc);
    w!(out, "///");
    w!(
        out,
        "/// The internal value is stored in `{}` (SI base unit).",
        qty.base_unit
    );
    w!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq, PartialOrd, Default)]"
    );
    w!(out, "pub struct {}(Num);", qty.name);
    w!(out);
}

// ── Unit enum ─────────────────────────────────────────────────────────────────

fn emit_enum(qty: &QuantityDef, out: &mut String) {
    w!(out, "/// Unit variants for [`{}`].", qty.name);
    w!(out, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    w!(out, "pub enum {}Unit {{", qty.name);
    for unit in &qty.units {
        if let Some(doc) = &unit.doc {
            let doc = escape_doc(doc);
            w!(out, "    /// {}", doc);
        }
        w!(out, "    {},", unit.singular);
    }
    w!(out, "}}");
    w!(out);
}

// ── impl on the enum ──────────────────────────────────────────────────────────

fn emit_enum_impl(qty: &QuantityDef, out: &mut String) {
    let enum_name = format!("{}Unit", qty.name);

    w!(out, "impl {} {{", enum_name);

    // ALL constant
    w!(out, "    /// Every unit variant for this quantity.");
    w!(out, "    pub const ALL: &'static [Self] = &[");
    for unit in &qty.units {
        w!(out, "        Self::{},", unit.singular);
    }
    w!(out, "    ];");
    w!(out);

    // abbreviation()
    w!(
        out,
        "    /// Returns the primary display abbreviation for this unit."
    );
    w!(out, "    pub fn abbreviation(self) -> &'static str {{");
    w!(out, "        match self {{");
    for unit in &qty.units {
        let abbr = rust_str_literal(&unit.abbreviation);
        w!(out, "            Self::{} => {},", unit.singular, abbr);
    }
    w!(out, "        }}");
    w!(out, "    }}");
    w!(out);

    // all_abbreviations()
    w!(
        out,
        "    /// Returns all abbreviations recognised during [`FromStr`] parsing."
    );
    w!(
        out,
        "    pub fn all_abbreviations(self) -> &'static [&'static str] {{"
    );
    w!(out, "        match self {{");
    for unit in &qty.units {
        let abbrs: Vec<String> = unit
            .all_abbreviations
            .iter()
            .map(|a| rust_str_literal(a))
            .collect();
        let list = abbrs.join(", ");
        w!(out, "            Self::{} => &[{}],", unit.singular, list);
    }
    w!(out, "        }}");
    w!(out, "    }}");

    w!(out, "}}");
    w!(out);
}

// ── impl on the struct ────────────────────────────────────────────────────────

fn emit_struct_impl(qty: &QuantityDef, out: &mut String) {
    let name = &qty.name;
    let enum_name = format!("{name}Unit");

    w!(out, "impl {} {{", name);

    // new()
    w!(
        out,
        "    /// Creates a new value from `value` expressed in `unit`."
    );
    w!(
        out,
        "    pub fn new(value: Num, unit: {}) -> Self {{",
        enum_name
    );
    w!(
        out,
        "        // `x` is the idiomatic variable name used in the generated formulas."
    );
    w!(out, "        let x = value;");
    w!(out, "        Self(match unit {{");
    for unit in &qty.units {
        w!(
            out,
            "            {}::{} => {},",
            enum_name,
            unit.singular,
            unit.to_base
        );
    }
    w!(out, "        }})");
    w!(out, "    }}");
    w!(out);

    // as_base / from_base
    w!(
        out,
        "    /// Returns the raw value stored in the SI base unit."
    );
    w!(out, "    ///");
    w!(
        out,
        "    /// Used for cross-type arithmetic (e.g. `Length / Duration = Speed`)."
    );
    w!(out, "    #[inline]");
    w!(out, "    pub fn as_base(self) -> Num {{ self.0 }}");
    w!(out);
    w!(out, "    /// Wraps a raw base-unit value into this type.");
    w!(out, "    ///");
    w!(out, "    /// Used for cross-type arithmetic.");
    w!(out, "    #[inline]");
    w!(
        out,
        "    pub fn from_base(value: Num) -> Self {{ Self(value) }}"
    );
    w!(out);

    // convert_to()
    w!(out, "    /// Returns the quantity expressed in `unit`.");
    w!(
        out,
        "    pub fn convert_to(self, unit: {}) -> Num {{",
        enum_name
    );
    w!(out, "        let x = self.0;");
    w!(out, "        match unit {{");
    for unit in &qty.units {
        w!(
            out,
            "            {}::{} => {},",
            enum_name,
            unit.singular,
            unit.from_base
        );
    }
    w!(out, "        }}");
    w!(out, "    }}");
    w!(out);

    // Per-unit convenience constructors and accessors.
    for unit in &qty.units {
        let snake_plural = unit.plural.to_snake_case();
        let snake_singular = unit.singular.to_snake_case();
        let abbr = &unit.abbreviation;

        w!(
            out,
            "    /// Creates a [`{}`] from a value in {} (`{}`).",
            name,
            unit.plural,
            abbr
        );
        w!(out, "    #[inline]");
        w!(
            out,
            "    pub fn from_{}(value: Num) -> Self {{",
            snake_plural
        );
        w!(
            out,
            "        Self::new(value, {}::{})",
            enum_name,
            unit.singular
        );
        w!(out, "    }}");
        w!(out);

        w!(
            out,
            "    /// Returns the value expressed in {} (`{}`).",
            unit.plural,
            abbr
        );
        w!(out, "    #[inline]");
        w!(out, "    pub fn as_{}(self) -> Num {{", snake_plural);
        w!(
            out,
            "        self.convert_to({}::{})",
            enum_name,
            unit.singular
        );
        w!(out, "    }}");

        // Emit singular alias only when it differs from the plural form.
        if snake_singular != snake_plural {
            w!(out);
            w!(out, "    /// Alias for [`Self::as_{}`].", snake_plural);
            w!(out, "    #[inline]");
            w!(out, "    pub fn as_{}(self) -> Num {{", snake_singular);
            w!(out, "        self.as_{}()", snake_plural);
            w!(out, "    }}");
        }
        w!(out);
    }

    w!(out, "}}");
    w!(out);
}

// ── Arithmetic trait impls ────────────────────────────────────────────────────

fn emit_arithmetic(qty: &QuantityDef, out: &mut String) {
    let n = &qty.name;
    w!(out, "impl Add for {} {{ type Output = {}; fn add(self, rhs: Self) -> Self {{ Self(self.0 + rhs.0) }} }}", n, n);
    w!(out, "impl Sub for {} {{ type Output = {}; fn sub(self, rhs: Self) -> Self {{ Self(self.0 - rhs.0) }} }}", n, n);
    w!(
        out,
        "impl Neg for {} {{ type Output = {}; fn neg(self) -> Self {{ Self(-self.0) }} }}",
        n,
        n
    );
    w!(out, "impl Mul<Num> for {} {{ type Output = {}; fn mul(self, rhs: Num) -> Self {{ Self(self.0 * rhs) }} }}", n, n);
    w!(out, "impl Mul<{}> for Num {{ type Output = {}; fn mul(self, rhs: {}) -> {} {{ {}(self * rhs.0) }} }}", n, n, n, n, n);
    w!(out, "impl Div<Num> for {} {{ type Output = {}; fn div(self, rhs: Num) -> Self {{ Self(self.0 / rhs) }} }}", n, n);
    w!(out, "impl Div for {} {{ type Output = Num; fn div(self, rhs: Self) -> Num {{ self.0 / rhs.0 }} }}", n);
    w!(out);
}

// ── Display ───────────────────────────────────────────────────────────────────

fn emit_display(qty: &QuantityDef, out: &mut String) {
    let name = &qty.name;
    let base = &qty.base_unit;

    w!(out, "impl fmt::Display for {} {{", name);
    w!(
        out,
        "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{"
    );
    w!(
        out,
        "        write!(f, \"{{}} {{}}\", self.0, {}Unit::{}.abbreviation())",
        name,
        base
    );
    w!(out, "    }}");
    w!(out, "}}");
    w!(out);
}

// ── FromStr ───────────────────────────────────────────────────────────────────

fn emit_from_str(qty: &QuantityDef, out: &mut String) {
    let name = &qty.name;
    let err_name = format!("Parse{name}Error");

    w!(
        out,
        "/// Error returned when a string cannot be parsed as a [`{}`].",
        name
    );
    w!(out, "#[derive(Debug)]");
    w!(out, "pub struct {}(String);", err_name);
    w!(out);
    w!(out, "impl fmt::Display for {} {{", err_name);
    w!(
        out,
        "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{"
    );
    w!(
        out,
        "        write!(f, \"cannot parse {{:?}} as {}\", self.0)",
        name
    );
    w!(out, "    }}");
    w!(out, "}}");
    w!(out);
    w!(out, "impl std::error::Error for {} {{}}", err_name);
    w!(out);

    // Build sorted (abbreviation, variant) list at codegen time.
    let mut map: Vec<(&str, &str)> = qty
        .units
        .iter()
        .flat_map(|u| {
            u.all_abbreviations
                .iter()
                .map(move |a| (a.as_str(), u.singular.as_str()))
        })
        .filter(|(a, _)| !a.is_empty())
        .collect();
    // Longest abbreviation first so "km/s" is tried before "m/s".
    map.sort_by(|a, b| b.0.len().cmp(&a.0.len()).then(a.0.cmp(b.0)));
    map.dedup_by_key(|e| e.0);

    w!(out, "impl FromStr for {} {{", name);
    w!(out, "    type Err = {};", err_name);
    w!(out);
    w!(
        out,
        "    fn from_str(s: &str) -> Result<Self, Self::Err> {{"
    );
    w!(out, "        let s = s.trim();");
    w!(
        out,
        "        // Find the end of the numeric part by scanning for the last digit or '.'."
    );
    w!(out, "        let split = s");
    w!(
        out,
        "            .rfind(|c: char| c.is_ascii_digit() || c == '.')"
    );
    w!(out, "            .map(|i| i + c_len_at(s, i))");
    w!(out, "            .unwrap_or(0);");
    w!(out, "        let (num_str, unit_str) = s.split_at(split);");
    w!(out, "        let value: Num = num_str");
    w!(out, "            .trim()");
    w!(out, "            .parse()");
    w!(
        out,
        "            .map_err(|_| {}(s.to_owned()))?;",
        err_name
    );
    w!(out, "        let unit_str = unit_str.trim();");
    w!(out);
    w!(out, "        const MAP: &[(&str, {}Unit)] = &[", name);
    for (abbr, variant) in &map {
        let abbr_lit = rust_str_literal(abbr);
        w!(
            out,
            "            ({}, {}Unit::{}),",
            abbr_lit,
            name,
            variant
        );
    }
    w!(out, "        ];");
    w!(out);
    w!(out, "        for &(abbr, unit) in MAP {{");
    w!(out, "            if unit_str == abbr {{");
    w!(out, "                return Ok(Self::new(value, unit));");
    w!(out, "            }}");
    w!(out, "        }}");
    w!(out, "        Err({}(s.to_owned()))", err_name);
    w!(out, "    }}");
    w!(out, "}}");
    w!(out);

    w!(
        out,
        "/// Returns the byte length of the UTF-8 char starting at byte index `i` in `s`."
    );
    w!(out, "#[inline]");
    w!(out, "fn c_len_at(s: &str, i: usize) -> usize {{");
    w!(out, "    s[i..].chars().next().map_or(1, |c| c.len_utf8())");
    w!(out, "}}");
}

// ── Cross-type arithmetic ─────────────────────────────────────────────────────

/// A single cross-type arithmetic relationship derived from dimensional analysis.
///
/// For example, `Length / Duration = Speed` is represented as:
/// ```text
/// CrossOp { lhs: "Length", rhs: "Duration", output: "Speed", trait_name: "Div" }
/// ```
pub struct CrossOp {
    /// Left-hand side type name (e.g. `"Length"`).
    pub lhs: String,
    /// Right-hand side type name (e.g. `"Duration"`).
    pub rhs: String,
    /// Result type name (e.g. `"Speed"`).
    pub output: String,
    /// Either `"Mul"` or `"Div"`.
    pub trait_name: String,
}

/// Generates the complete `src/cross_type.rs` source from the supplied operations.
///
/// Every impl routes through `as_base()` / `from_base()` so the arithmetic is
/// correct regardless of which display unit the caller used to construct the value.
pub fn generate_cross_type(ops: &[CrossOp]) -> String {
    let mut out = String::with_capacity(4 * 1024);

    w!(
        out,
        "// Code generated by `cargo run -p codegen` \u{2014} DO NOT EDIT"
    );
    w!(
        out,
        "//! Cross-type arithmetic relationships derived from dimensional analysis."
    );

    if ops.is_empty() {
        return out;
    }

    w!(out);

    // Collect all trait names and type names referenced by the ops.
    let traits: BTreeSet<&str> = ops.iter().map(|o| o.trait_name.as_str()).collect();
    let trait_list = traits.into_iter().collect::<Vec<_>>().join(", ");
    w!(out, "use std::ops::{{{}}};", trait_list);
    w!(out);

    let mut types: BTreeSet<&str> = BTreeSet::new();
    for op in ops {
        types.insert(&op.lhs);
        types.insert(&op.rhs);
        types.insert(&op.output);
    }
    for t in &types {
        w!(out, "use crate::units::{}::{};", t.to_snake_case(), t);
    }
    w!(out);

    for op in ops {
        let (method, operator) = if op.trait_name == "Mul" {
            ("mul", "*")
        } else {
            ("div", "/")
        };

        w!(
            out,
            "// ── {} {} {} = {} ──",
            op.lhs,
            operator,
            op.rhs,
            op.output
        );
        w!(out);
        w!(out, "impl {}<{}> for {} {{", op.trait_name, op.rhs, op.lhs);
        w!(out, "    type Output = {};", op.output);
        w!(out);
        w!(out, "    #[inline]");
        w!(
            out,
            "    fn {}(self, rhs: {}) -> {} {{",
            method,
            op.rhs,
            op.output
        );
        w!(
            out,
            "        {}::from_base(self.as_base() {} rhs.as_base())",
            op.output,
            operator
        );
        w!(out, "    }}");
        w!(out, "}}");
        w!(out);
    }

    out
}

// ── Integration test file ─────────────────────────────────────────────────────

/// Generates the content of `tests/<quantity_snake>.rs` for a single quantity.
///
/// Each file is a self-contained Cargo integration test binary, so there is no
/// wrapping `mod` — test functions sit at the file root and use the public API
/// via `use unitsnet_rs::*`.
pub fn generate_quantity_tests(qty: &QuantityDef) -> String {
    let mut out = String::with_capacity(16 * 1024);
    let name = &qty.name;
    let enum_name = format!("{}Unit", name);

    w!(
        out,
        "// Code generated by `cargo run -p codegen` \u{2014} DO NOT EDIT"
    );
    w!(out, "// Quantity: {}", name);
    w!(out);
    w!(out, "use unitsnet_rs::*;");
    w!(out);
    // Round-trip tolerance: f32 has ~7 significant digits so 1e-5 is safe;
    // f64 has ~15 digits so 1e-9 is safe. Arithmetic tests (exact integer
    // base-unit ops) stay at 1e-12 for both because IEEE 754 guarantees them.
    w!(out, "#[cfg(feature = \"f32\")]");
    w!(out, "const RT_EPS: Num = 1e-5;");
    w!(out, "#[cfg(not(feature = \"f32\"))]");
    w!(out, "const RT_EPS: Num = 1e-9;");
    w!(out);

    // Round-trip: from_X(v).as_X() ≈ v validates both conversion formulas.
    //
    // We use v = 1_000_000 (exactly representable in both f32 and f64) and a
    // *relative* tolerance so that units with large additive offsets (e.g.
    // MillidegreesCelsius: x/1000 + 273.15) don't fail due to catastrophic
    // cancellation.  With v >> offset, the relative error stays within RT_EPS
    // for both f32 (~1e-7) and f64 (~1e-16).
    for unit in &qty.units {
        let snake = unit.plural.to_snake_case();
        w!(out, "#[test]");
        w!(out, "fn round_trip_{}() {{", snake);
        // 1_000_000 is exactly representable in f32 (< 2^23 = 8_388_608).
        w!(out, "    let v: Num = 1_000_000.0;");
        w!(
            out,
            "    assert!(({}::from_{}(v).as_{}() - v).abs() / v < RT_EPS);",
            name,
            snake,
            snake
        );
        w!(out, "}}");
        w!(out);
    }

    // Arithmetic smoke tests on exact base-unit values.
    w!(out, "#[test]");
    w!(out, "fn test_add() {{");
    w!(out, "    let a = {}::from_base(2.0);", name);
    w!(out, "    let b = {}::from_base(3.0);", name);
    w!(out, "    assert!(((a + b).as_base() - 5.0).abs() < 1e-12);");
    w!(out, "}}");
    w!(out);

    w!(out, "#[test]");
    w!(out, "fn test_sub() {{");
    w!(out, "    let a = {}::from_base(5.0);", name);
    w!(out, "    let b = {}::from_base(3.0);", name);
    w!(out, "    assert!(((a - b).as_base() - 2.0).abs() < 1e-12);");
    w!(out, "}}");
    w!(out);

    w!(out, "#[test]");
    w!(out, "fn test_neg() {{");
    w!(
        out,
        "    assert!(((-{}::from_base(4.0)).as_base() + 4.0).abs() < 1e-12);",
        name
    );
    w!(out, "}}");
    w!(out);

    w!(out, "#[test]");
    w!(out, "fn test_mul_num() {{");
    w!(
        out,
        "    assert!((({}::from_base(4.0) * 2.0).as_base() - 8.0).abs() < 1e-12);",
        name
    );
    w!(out, "}}");
    w!(out);

    w!(out, "#[test]");
    w!(out, "fn test_div_num() {{");
    w!(
        out,
        "    assert!((({}::from_base(6.0) / 2.0).as_base() - 3.0).abs() < 1e-12);",
        name
    );
    w!(out, "}}");
    w!(out);

    w!(out, "#[test]");
    w!(out, "fn test_div_same_type() {{");
    w!(
        out,
        "    assert!(({}::from_base(6.0) / {}::from_base(2.0) - 3.0).abs() < 1e-12);",
        name,
        name
    );
    w!(out, "}}");
    w!(out);

    // FromStr: parse "1 <abbr>" and compare to the direct constructor.
    // Skipped when the base unit has no abbreviation.
    if let Some(base) = qty.units.iter().find(|u| u.singular == qty.base_unit) {
        if !base.abbreviation.is_empty() {
            let snake_base = base.plural.to_snake_case();
            w!(out, "#[test]");
            w!(out, "fn from_str_base_unit() {{");
            w!(
                out,
                "    let abbr = {}::{}.abbreviation();",
                enum_name,
                base.singular
            );
            w!(out, "    let s = format!(\"1 {{}}\", abbr);");
            w!(
                out,
                "    let parsed: {} = s.parse().expect(\"parse failed\");",
                name
            );
            // Use relative tolerance: same reasoning as the round-trip tests above.
            w!(
                out,
                "    let expected = {}::from_{}(1.0).as_base();",
                name,
                snake_base
            );
            w!(
                out,
                "    assert!((parsed.as_base() - expected).abs() / expected.abs().max(1.0) < RT_EPS);"
            );
            w!(out, "}}");
            w!(out);
        }
    }

    out
}

/// Generates `tests/cross_type.rs` — one test per cross-type arithmetic op.
///
/// These tests only exercise exact base-unit arithmetic (`6 * 2 = 12`),
/// which is representable without rounding in both f32 and f64.
pub fn generate_cross_type_tests(ops: &[CrossOp]) -> String {
    let mut out = String::with_capacity(32 * 1024);

    w!(
        out,
        "// Code generated by `cargo run -p codegen` \u{2014} DO NOT EDIT"
    );
    w!(out);
    w!(out, "use unitsnet_rs::*;");
    w!(out);

    for op in ops {
        let op_sym = if op.trait_name == "Mul" { "*" } else { "/" };
        let (lhs_v, rhs_v, expected) = if op.trait_name == "Mul" {
            ("6.0", "2.0", "12.0")
        } else {
            ("6.0", "2.0", "3.0")
        };
        let test_name = format!(
            "{}_{}_{}_gives_{}",
            op.trait_name.to_lowercase(),
            op.lhs.to_snake_case(),
            op.rhs.to_snake_case(),
            op.output.to_snake_case(),
        );
        w!(out, "#[test]");
        w!(out, "fn {}() {{", test_name);
        w!(out, "    let a = {}::from_base({});", op.lhs, lhs_v);
        w!(out, "    let b = {}::from_base({});", op.rhs, rhs_v);
        w!(out, "    let c: {} = a {} b;", op.output, op_sym);
        w!(
            out,
            "    assert!((c.as_base() - {}).abs() < 1e-12);",
            expected
        );
        w!(out, "}}");
        w!(out);
    }

    out
}

