/// Storage types that support unit conversions: the arithmetic operators and
/// a way to turn a conversion constant into a value.
///
/// Implemented for `f32`, `f64` and `Uncertain`, and with features for
/// `Complex<f32>` and `Complex<f64>` (`num-complex`), `Decimal`
/// (`rust_decimal`) and `Ratio<i32>`, `Ratio<i64>` and `Ratio<i128>`
/// (`num-rational`). Conversions, `new`, the `from_`/`as_` methods,
/// relations with a factor and [`formula!`] need only this; ordering,
/// rounding, parsing and automatic units need [`Float`].
///
/// ```rust
/// # #[cfg(feature = "num-rational")] {
/// use num_rational::Ratio;
/// use qty::*;
///
/// let third = Length::from_feet(Ratio::<i64>::new(1, 3));
/// assert_eq!(third.as_meters(), Ratio::new(127, 1250));
/// assert_eq!((third + third + third).as_feet(), Ratio::from_integer(1));
/// # }
/// ```
///
/// To store quantities in your own type, implement
/// [`from_f64`](Number::from_f64). Multiplying or dividing a quantity by a
/// plain number of your own type needs it too. The other methods have defaults that
/// evaluate fractions such as 5/9 exactly when the type can.
pub trait Number:
    Copy
    + Add<Output = Self>
    + Sub<Output = Self>
    + Mul<Output = Self>
    + Div<Output = Self>
    + Neg<Output = Self>
{
    /// Converts a conversion constant to `Self`, rounding to nearest. It's
    /// always called with a literal, so for `f32` and `f64` this happens at
    /// compile time.
    fn from_f64(value: f64) -> Self;

    /// `numerator / denominator`, for conversion constants such as 5/9 that
    /// have no exact decimal. Both are whole numbers. Exact types such as
    /// rationals get the exact fraction from the default; floats override
    /// it to round once.
    #[inline]
    fn from_ratio(numerator: f64, denominator: f64) -> Self {
        Self::from_f64(numerator) / Self::from_f64(denominator)
    }

    /// `self · numerator / denominator`, for conversions such as km/h to m/s
    /// (5/18). Floats override it to multiply once by the rounded fraction.
    #[inline]
    fn mul_ratio(self, numerator: f64, denominator: f64) -> Self {
        self * Self::from_f64(numerator) / Self::from_f64(denominator)
    }

    /// `self / (numerator / denominator)`, the inverse of
    /// [`mul_ratio`](Number::mul_ratio). Floats override it to divide once
    /// by the rounded fraction.
    #[inline]
    fn div_ratio(self, numerator: f64, denominator: f64) -> Self {
        self * Self::from_f64(denominator) / Self::from_f64(numerator)
    }
}

/// Floating-point storage types: a [`Number`] with an order, as needed for
/// comparisons, `abs`, `min` and `max`, rounding, parsing and automatic
/// units.
///
/// Implemented for `f32`, `f64` and `Uncertain`. Implement it, and
/// [`Number`], for your own type, such as a half-precision float or a dual
/// number for automatic differentiation, to get all of the above on it.
///
/// Arithmetic operators don't need this trait. They work for any storage
/// type that has the operator, integers included.
pub trait Float: Number + ToFloat + fmt::Debug + PartialOrd {
    /// Absolute value.
    fn abs(self) -> Self;

    /// The larger of two values (ignoring NaN, like [`f64::max`]).
    fn max(self, other: Self) -> Self;

    /// The smaller of two values (ignoring NaN, like [`f64::min`]).
    fn min(self, other: Self) -> Self;

    /// IEEE 754 total order, like [`f64::total_cmp`].
    fn total_cmp(&self, other: &Self) -> core::cmp::Ordering;

    /// `true` unless the value is NaN or infinite.
    fn is_finite(self) -> bool;

    /// `true` for NaN.
    #[inline]
    fn is_nan(self) -> bool {
        #[allow(clippy::eq_op)]
        let nan = self != self;
        nan
    }

    /// `true` for negative values, `-0.0` included (like
    /// [`f64::is_sign_negative`]).
    #[inline]
    fn is_sign_negative(self) -> bool {
        let zero = Self::from_f64(0.0);
        self < zero || (self == zero && Self::from_f64(1.0) / self < zero)
    }
}

macro_rules! impl_float {
    ($($t:ident: $sign:expr),*) => {$(
        impl Number for $t {
            #[inline(always)]
            fn from_f64(value: f64) -> Self {
                value as $t
            }

            // The fraction rounds to the same `f64` as its literal would,
            // and folds to a constant.
            #[inline(always)]
            fn from_ratio(numerator: f64, denominator: f64) -> Self {
                (numerator / denominator) as $t
            }

            #[inline(always)]
            fn mul_ratio(self, numerator: f64, denominator: f64) -> Self {
                self * Self::from_ratio(numerator, denominator)
            }

            #[inline(always)]
            fn div_ratio(self, numerator: f64, denominator: f64) -> Self {
                self / Self::from_ratio(numerator, denominator)
            }
        }

        impl Float for $t {
            #[inline(always)]
            fn abs(self) -> Self {
                // Clear the sign bit. (`abs` itself is only in `core` since
                // Rust 1.85; this compiles to the same single instruction.)
                $t::from_bits(self.to_bits() & !$sign)
            }
            #[inline(always)]
            fn max(self, other: Self) -> Self {
                $t::max(self, other)
            }
            #[inline(always)]
            fn min(self, other: Self) -> Self {
                $t::min(self, other)
            }
            #[inline(always)]
            fn total_cmp(&self, other: &Self) -> core::cmp::Ordering {
                $t::total_cmp(self, other)
            }
            #[inline(always)]
            fn is_finite(self) -> bool {
                $t::is_finite(self)
            }
            #[inline(always)]
            fn is_nan(self) -> bool {
                $t::is_nan(self)
            }
            #[inline(always)]
            fn is_sign_negative(self) -> bool {
                $t::is_sign_negative(self)
            }
        }
    )*};
}
impl_float!(f32: 1 << 31, f64: 1 << 63);

/// Math functions on float storage, for `sqrt`, trigonometry and `hypot` on
/// quantities. Available with the `std` feature (default) or, on `no_std`
/// targets, the `libm` feature.
#[cfg(any(feature = "std", feature = "libm"))]
pub trait FloatMath: Float {
    /// Square root.
    fn sqrt(self) -> Self;
    /// Cube root.
    fn cbrt(self) -> Self;
    /// Sine (radians).
    fn sin(self) -> Self;
    /// Cosine (radians).
    fn cos(self) -> Self;
    /// Tangent (radians).
    fn tan(self) -> Self;
    /// Arcsine, in radians.
    fn asin(self) -> Self;
    /// Arccosine, in radians.
    fn acos(self) -> Self;
    /// Arctangent, in radians.
    fn atan(self) -> Self;
    /// Four-quadrant arctangent of `self / other`, in radians.
    fn atan2(self, other: Self) -> Self;
    /// `sqrt(self² + other²)` without intermediate overflow.
    fn hypot(self, other: Self) -> Self;
    /// Nearest integer, ties away from zero.
    fn round(self) -> Self;
    /// Largest integer not above.
    fn floor(self) -> Self;
    /// Smallest integer not below.
    fn ceil(self) -> Self;
}

#[cfg(any(feature = "std", feature = "libm"))]
macro_rules! impl_float_math {
    ($t:ident, $($method:ident($($arg:ident),*) => $libm:ident),*) => {
        impl FloatMath for $t {$(
            #[inline(always)]
            fn $method(self $(, $arg: Self)*) -> Self {
                // `std` provides inherent methods; prefer them when present.
                #[cfg(feature = "std")]
                return $t::$method(self $(, $arg)*);
                #[cfg(not(feature = "std"))]
                return libm::$libm(self $(, $arg)*);
            }
        )*}
    };
}
#[cfg(any(feature = "std", feature = "libm"))]
impl_float_math!(f64,
    sqrt() => sqrt, cbrt() => cbrt, sin() => sin, cos() => cos, tan() => tan,
    asin() => asin, acos() => acos, atan() => atan,
    atan2(other) => atan2, hypot(other) => hypot,
    round() => round, floor() => floor, ceil() => ceil);
#[cfg(any(feature = "std", feature = "libm"))]
impl_float_math!(f32,
    sqrt() => sqrtf, cbrt() => cbrtf, sin() => sinf, cos() => cosf, tan() => tanf,
    asin() => asinf, acos() => acosf, atan() => atanf,
    atan2(other) => atan2f, hypot(other) => hypotf,
    round() => roundf, floor() => floorf, ceil() => ceilf);

/// Implemented by every quantity, for code that is generic over quantities.
///
/// In other code, call the inherent methods with the same names.
pub trait Quantity: Copy {
    /// The numeric storage type (`f64` unless specified).
    type Value: Copy;

    /// The enum listing every unit of this quantity.
    type Unit: UnitEnum;

    /// The unit in which values are stored.
    const BASE_UNIT: Self::Unit;

    /// Name, description, dimensions and units of the quantity.
    const INFO: QuantityInfo;

    /// The base unit as a unit expression, for reading expressions and for
    /// `relation!`. It's the base unit's abbreviation when that is an
    /// expression with the quantity's dimensions. Built-in quantities whose
    /// abbreviation isn't (`∆K`, `Ns/m²`) get it from UnitsNet's data.
    #[doc(hidden)]
    const BASE_UNIT_EXPR: Option<UnitExpr> = custom::private::base_unit_expr(Self::INFO, None);

    /// Wraps a value expressed in [`Self::BASE_UNIT`].
    fn from_base(value: Self::Value) -> Self;

    /// Returns the value expressed in [`Self::BASE_UNIT`].
    fn as_base(self) -> Self::Value;

    /// A quantity from a value in `unit`, like the inherent `new`.
    ///
    /// ```rust
    /// use qty::*;
    ///
    /// fn in_kilo<Q: Quantity<Value = f64>>(value: f64, kilo: Q::Unit, base: Q::Unit) -> f64 {
    ///     Q::new(value, kilo).convert_to(base)
    /// }
    /// assert_eq!(in_kilo::<Length>(1.5, LengthUnit::Kilometer, LengthUnit::Meter), 1500.0);
    /// ```
    fn new(value: Self::Value, unit: Self::Unit) -> Self
    where
        Self::Value: Number;

    /// The value expressed in `unit`, like the inherent `convert_to`.
    fn convert_to(self, unit: Self::Unit) -> Self::Value
    where
        Self::Value: Number;

    /// This quantity to the whole power `N`, which can be negative. The
    /// result is what `*` and `/` give for the same product: the quantity
    /// with those dimensions, or a [`formula::Expr`] where no quantity has
    /// them.
    ///
    /// ```rust
    /// use qty::*;
    ///
    /// let side = Length::from_meters(3.0);
    /// let floor: Area = side.powi::<2>();
    /// assert_eq!(floor, side * side);
    ///
    /// let (m, v) = (Mass::from_kilograms(70.0), Speed::from_meters_per_second(3.0));
    /// let e: Energy = 0.5 * m * v.powi::<2>();
    /// assert_eq!(e.as_joules(), 315.0);
    ///
    /// let rate: Frequency = Duration::from_seconds(0.5).powi::<-1>();
    /// assert_eq!(rate.as_hertz(), 2.0);
    /// ```
    #[inline(always)]
    fn powi<const N: i8>(self) -> arith::PowOut<Self, N>
    where
        Self: arith::Arith<Value = <Self as Quantity>::Value>,
        <Self as Quantity>::Value: Number,
        <Self as arith::Arith>::Dim: formula::PowDim<N>,
        <<Self as arith::Arith>::Dim as formula::PowDim<N>>::Out:
            arith::Canon<<Self as Quantity>::Value>,
    {
        arith::powi::<Self, N>(self)
    }
}

/// Implemented by every unit enum (`LengthUnit`, `MassUnit`, …).
pub trait UnitEnum: Unit {
    /// Every unit of the quantity.
    const ALL: &'static [Self];
}

/// A unit: its abbreviation and names. Implemented by every unit enum and,
/// with the `dynamic` feature, by `AnyUnit`.
pub trait Unit: Copy + Eq + core::hash::Hash + fmt::Debug + fmt::Display + 'static {
    /// The abbreviation shown when printing, like `"km"`.
    fn abbreviation(self) -> &'static str;

    /// Names and abbreviations.
    fn info(self) -> &'static UnitInfo;
}

/// A value expressed in a given unit, as returned by `in_unit` and
/// `auto_unit`. Formats as the number followed by the unit's abbreviation,
/// applying format flags to the number:
///
/// ```rust
/// use qty::*;
///
/// let d = Length::from_meters(1234.5);
/// assert_eq!(d.in_unit(LengthUnit::Kilometer).to_string(), "1.2345 km");
/// assert_eq!(format!("{:.1}", d.in_unit(LengthUnit::Kilometer)), "1.2 km");
/// assert_eq!(format!("{:.2}", Length::from_meters(0.0025).auto_unit()), "2.50 mm");
///
/// // The parts are available too.
/// let InUnit { value, unit } = d.auto_unit();
/// assert_eq!((value, unit), (1.2345, LengthUnit::Kilometer));
/// ```
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct InUnit<T, U> {
    /// The numeric value, expressed in `unit`.
    pub value: T,
    /// The unit `value` is expressed in.
    pub unit: U,
}

macro_rules! in_unit_fmt {
    ($($Trait:ident),*) => {$(
        impl<T: fmt::$Trait, U: Unit> fmt::$Trait for InUnit<T, U> {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::$Trait::fmt(&self.value, f)?;
                let abbr = self.unit.abbreviation();
                if abbr.is_empty() {
                    Ok(())
                } else {
                    write!(f, " {abbr}")
                }
            }
        }
    )*};
}
in_unit_fmt!(Display, LowerExp, UpperExp);

/// Approximate comparison of float quantities. Every quantity implements it.
///
/// [`approx_eq_abs`](ApproxEq::approx_eq_abs) allows a fixed difference,
/// which suits values of a known size. [`approx_eq_rel`](ApproxEq::approx_eq_rel)
/// scales the allowed difference with the values. [`approx_eq`](ApproxEq::approx_eq)
/// passes if either test does, so it also works near zero. Tolerances are
/// in the base unit.
///
/// # Examples
///
/// ```rust
/// use qty::*;
///
/// let a = Length::from_meters(1.0);
/// let b = Length::from_centimeters(100.0);
///
/// // Absolute: difference must be under 1 nanometre.
/// assert!(a.approx_eq_abs(b, 1e-9));
///
/// // Relative: difference must be under 1 part per billion.
/// assert!(a.approx_eq_rel(b, 1e-9));
///
/// // Either: works near zero too.
/// assert!(a.approx_eq(b, 1e-12, 1e-9));
/// ```
pub trait ApproxEq: Quantity {
    /// Returns `true` if `|self − other| ≤ epsilon`.
    fn approx_eq_abs(self, other: Self, epsilon: Self::Value) -> bool;

    /// Returns `true` if `|self − other| ≤ rel_tol × max(|self|, |other|)`.
    ///
    /// Returns `true` when both values are exactly zero. Typical tolerances:
    /// `1e-12` for `f64`, `1e-6` for `f32`.
    fn approx_eq_rel(self, other: Self, rel_tol: Self::Value) -> bool;

    /// Returns `true` if `|self − other| ≤ epsilon + rel_tol × max(|self|, |other|)`.
    ///
    /// The same test as NumPy's
    /// [`isclose`](https://numpy.org/doc/stable/reference/generated/numpy.isclose.html).
    fn approx_eq(self, other: Self, epsilon: Self::Value, rel_tol: Self::Value) -> bool;
}

impl<Q: Quantity> ApproxEq for Q
where
    Q::Value: Float,
{
    #[inline]
    fn approx_eq_abs(self, other: Self, epsilon: Self::Value) -> bool {
        (self.as_base() - other.as_base()).abs() <= epsilon
    }

    #[inline]
    fn approx_eq_rel(self, other: Self, rel_tol: Self::Value) -> bool {
        let (a, b) = (self.as_base(), other.as_base());
        // Also covers both being zero, where the relative test fails.
        a == b || (a - b).abs() <= rel_tol * a.abs().max(b.abs())
    }

    #[inline]
    fn approx_eq(self, other: Self, epsilon: Self::Value, rel_tol: Self::Value) -> bool {
        let (a, b) = (self.as_base(), other.as_base());
        (a - b).abs() <= epsilon + rel_tol * a.abs().max(b.abs())
    }
}

/// Error returned when parsing a quantity or a unit from a string fails.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum ParseError {
    /// The numeric part is missing or malformed.
    InvalidNumber,
    /// The unit abbreviation is not recognised for this quantity.
    UnknownUnit,
    /// The unit belongs to several quantities (`"m"`: metre or minute), so
    /// the kind cannot be told (runtime quantities, `dynamic` feature).
    Ambiguous,
}

impl fmt::Display for ParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            ParseError::InvalidNumber => "invalid number",
            ParseError::UnknownUnit => "unknown unit",
            ParseError::Ambiguous => "unit used by several quantities",
        })
    }
}

impl core::error::Error for ParseError {}

/// Normalises a unit *name* for matching: ASCII lowercase, without spaces,
/// `_` or `-`, with British "-re" spellings (metre, litre) turned into
/// "-er". Returns `None` for input that cannot be a name (non-ASCII, or
/// longer than the buffer).
#[doc(hidden)]
pub fn normalize_unit_name<'a>(name: &str, buf: &'a mut [u8; 64]) -> Option<&'a str> {
    let mut len = 0;
    for &b in name.trim().as_bytes() {
        if matches!(b, b' ' | b'_' | b'-') {
            continue;
        }
        if !b.is_ascii() || len == buf.len() {
            return None;
        }
        buf[len] = b.to_ascii_lowercase();
        len += 1;
    }
    let out = &mut buf[..len];
    for word in [&b"metre"[..], b"litre"] {
        let mut i = 0;
        while i + word.len() <= out.len() {
            if &out[i..i + word.len()] == word {
                out[i + word.len() - 2..i + word.len()].copy_from_slice(b"er");
                i += word.len();
            } else {
                i += 1;
            }
        }
    }
    core::str::from_utf8(out).ok()
}

/// Splits `"1.5e3 km/h"` into `("1.5e3", "km/h")`.
///
/// The number is the longest prefix matching a decimal float literal, so unit
/// abbreviations may themselves contain digits (`"2 m3"`) and the space is
/// optional (`"2m3"`).
#[doc(hidden)]
pub fn split_value_unit(s: &str) -> (&str, &str) {
    let s = s.trim();
    let b = s.as_bytes();
    let digits = |mut i: usize| {
        while i < b.len() && b[i].is_ascii_digit() {
            i += 1;
        }
        i
    };
    let mut i = 0;
    if i < b.len() && matches!(b[i], b'+' | b'-') {
        i += 1;
    }
    i = digits(i);
    if i < b.len() && b[i] == b'.' {
        i = digits(i + 1);
    }
    if i < b.len() && matches!(b[i], b'e' | b'E') {
        let mut j = i + 1;
        if j < b.len() && matches!(b[j], b'+' | b'-') {
            j += 1;
        }
        if j < b.len() && b[j].is_ascii_digit() {
            i = digits(j);
        }
    }
    (&s[..i], s[i..].trim_start())
}

/// `number * quantity` for the listed storage types. `quantity * number` is
/// generic, but the orphan rule rules out a generic impl with the number on
/// the left, hence the list.
///
/// `f32` is left out on purpose. With two float impls, `2.0 * q` would be
/// ambiguous until the type of `q` is known, and plain `f64` code would need
/// annotations. With `f32` storage, write `q * 2.0`.
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_scalar_lhs_mul {
    ($Q:ident: $($t:ty),*) => {$(
        impl ::core::ops::Mul<$Q<$t>> for $t {
            type Output = $Q<$t>;
            #[inline(always)]
            fn mul(self, rhs: $Q<$t>) -> $Q<$t> {
                $Q::from_base(self * rhs.0)
            }
        }
    )*};
}

/// `quantity * Vector2/Vector3` for the given storage types.
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_times_vector {
    ($Q:ident: $($t:ty),*) => {$(
        $crate::__qty_times_vector!(@impl $Q, [], $t, Vector2);
        $crate::__qty_times_vector!(@impl $Q, [], $t, Vector3);
    )*};
    ($Q:ident<$F:ident>: $t:ty) => {
        $crate::__qty_times_vector!(@impl $Q, [$F], $t, Vector2);
        $crate::__qty_times_vector!(@impl $Q, [$F], $t, Vector3);
    };
    (@impl $Q:ident, [$($F:ident)?], $t:ty, $V:ident) => {
        impl<$($F,)? R> ::core::ops::Mul<$crate::$V<R>> for $Q<$t>
        where
            $Q<$t>: ::core::ops::Mul<R> + Copy,
        {
            type Output = $crate::$V<<$Q<$t> as ::core::ops::Mul<R>>::Output>;
            #[inline(always)]
            fn mul(self, rhs: $crate::$V<R>) -> Self::Output {
                rhs.map(|c| self * c)
            }
        }
    };
}

/// Formats the value in the base unit followed by the unit abbreviation,
/// honouring precision and other flags:
/// `format!("{:.2}", Length::from_meters(1.0))` is `"1.00 m"` and
/// `format!("{:e}", Length::from_meters(1500.0))` is `"1.5e3 m"`.
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_fmt {
    ($Q:ident, $U:ident, $base:ident: $($Trait:ident),*) => {$(
        impl<T: ::core::fmt::$Trait> ::core::fmt::$Trait for $Q<T> {
            fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {
                ::core::fmt::$Trait::fmt(&self.0, f)?;
                $crate::__private::fmt_unit(f, $U::$base.abbreviation())
            }
        }
    )*};
}

/// What every quantity needs apart from unit conversions and arithmetic.
///
/// Used by the built-in quantities and by `custom_quantity!`, so it can
/// expand in other crates. That's why it names everything through `$crate`
/// and checks qty's features with the `__qty_if_*` switches. `exprs` is the
/// [`__private::Exprs`] mode for parsing.
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_common {
    ($Q:ident, $U:ident, $base:ident, exprs: $exprs:ident $(, si: $si:expr)?) => {
        impl<T> $Q<T> {
            /// Wraps a value in the base unit.
            #[inline(always)]
            pub const fn from_base(value: T) -> Self {
                Self(value)
            }

            /// Unwraps the value in the base unit. Unlike
            /// [`as_base`](Self::as_base), it works without `T: Copy`.
            #[inline(always)]
            pub fn into_base(self) -> T {
                self.0
            }

            /// Views a slice of base-unit values as quantities, without copying.
            #[inline(always)]
            pub const fn from_base_slice(values: &[T]) -> &[Self] {
                // SAFETY: `Self` is `#[repr(transparent)]` over `T`.
                unsafe { &*(values as *const [T] as *const [Self]) }
            }

            /// Views a mutable slice of base-unit values as quantities, without copying.
            #[inline(always)]
            pub fn from_base_slice_mut(values: &mut [T]) -> &mut [Self] {
                // SAFETY: `Self` is `#[repr(transparent)]` over `T`.
                unsafe { &mut *(values as *mut [T] as *mut [Self]) }
            }

            /// Views a slice of quantities as their base-unit values, without copying.
            #[inline(always)]
            pub const fn as_base_slice(values: &[Self]) -> &[T] {
                // SAFETY: `Self` is `#[repr(transparent)]` over `T`.
                unsafe { &*(values as *const [Self] as *const [T]) }
            }

            /// Views a mutable slice of quantities as their base-unit values, without copying.
            #[inline(always)]
            pub fn as_base_slice_mut(values: &mut [Self]) -> &mut [T] {
                // SAFETY: `Self` is `#[repr(transparent)]` over `T`.
                unsafe { &mut *(values as *mut [Self] as *mut [T]) }
            }

            /// Changes the storage type without loss, such as from `i32` to `f64`.
            #[inline(always)]
            pub fn cast<U: From<T>>(self) -> $Q<U> {
                $Q(U::from(self.0))
            }
        }

        impl<T: Copy> $Q<T> {
            /// The value in the base unit.
            #[inline(always)]
            pub const fn as_base(self) -> T {
                self.0
            }
        }

        impl<T: $crate::Float> $Q<T> {
            /// Absolute value.
            #[inline(always)]
            pub fn abs(self) -> Self {
                Self(self.0.abs())
            }

            /// `true` for NaN.
            #[inline(always)]
            pub fn is_nan(self) -> bool {
                self.0.is_nan()
            }

            /// `true` unless NaN or infinite.
            #[inline(always)]
            pub fn is_finite(self) -> bool {
                self.0.is_finite()
            }

            /// The larger of two quantities (ignoring NaN).
            #[inline(always)]
            pub fn max(self, other: Self) -> Self {
                Self(self.0.max(other.0))
            }

            /// The smaller of two quantities (ignoring NaN).
            #[inline(always)]
            pub fn min(self, other: Self) -> Self {
                Self(self.0.min(other.0))
            }

            /// Restricts to `[min, max]`, like [`f64::clamp`]: NaN stays NaN.
            ///
            /// # Panics
            ///
            /// If `min > max`.
            #[inline]
            pub fn clamp(self, min: Self, max: Self) -> Self {
                Self($crate::__private::clamp(self.0, min.0, max.0))
            }

            /// The mean of `values`, or `None` if there are none.
            ///
            /// It's the first value plus the mean difference from it, so it
            /// works for points too: the mean of 20 °C and 30 °C is 25 °C.
            /// With `Uncertain` storage this overstates the uncertainty, as the
            /// first value enters every difference. Sum and divide instead.
            pub fn mean<I: IntoIterator<Item = Self>>(values: I) -> ::core::option::Option<Self> {
                $crate::__private::mean(values)
            }

            /// Linear interpolation from `self` at `t = 0` to `other` at
            /// `t = 1`. Outside `[0, 1]` it extrapolates. Works for points
            /// too: halfway between 10 °C and 20 °C is 15 °C.
            #[inline]
            pub fn lerp(self, other: Self, t: T) -> Self {
                Self(self.0 + (other.0 - self.0) * t)
            }

            /// Total order, like [`f64::total_cmp`], for
            /// `values.sort_by(Length::total_cmp)`. For map keys, see
            /// [`Ordered`](qty::Ordered).
            #[inline(always)]
            pub fn total_cmp(&self, other: &Self) -> ::core::cmp::Ordering {
                self.0.total_cmp(&other.0)
            }
        }

        impl<T: $crate::ToFloat> $Q<T> {
            /// Converts the storage to `f64` the way `as f64` does, such as
            /// `Length<i64>` to `Length<f64>`.
            #[inline(always)]
            pub fn to_f64(self) -> $Q<f64> {
                $Q(self.0.to_f64())
            }

            /// Converts the storage to `f32` the way `as f32` does.
            #[inline(always)]
            pub fn to_f32(self) -> $Q<f32> {
                $Q(self.0.to_f32())
            }
        }

        impl<T: Copy> $crate::Quantity for $Q<T> {
            type Value = T;
            type Unit = $U;
            const BASE_UNIT: $U = $U::$base;
            const INFO: $crate::QuantityInfo = $U::QUANTITY;
            $(
                const BASE_UNIT_EXPR: ::core::option::Option<$crate::UnitExpr> =
                    $crate::__private::base_unit_expr($U::QUANTITY, $si);
            )?
            #[inline(always)]
            fn from_base(value: T) -> Self {
                Self(value)
            }
            #[inline(always)]
            fn as_base(self) -> T {
                self.0
            }
            #[inline]
            fn new(value: T, unit: $U) -> Self
            where
                T: $crate::Number,
            {
                $Q::new(value, unit)
            }
            #[inline]
            fn convert_to(self, unit: $U) -> T
            where
                T: $crate::Number,
            {
                $Q::convert_to(self, unit)
            }
        }

        // `mass * acceleration_vector`, for concrete storage types only: a
        // generic impl would overlap with `$Q<T> * T` when `T` is a vector.
        $crate::__qty_times_vector!($Q: f64, f32);
        $crate::__qty_if_math! {
            $crate::__qty_times_vector!($Q<F>: $crate::Uncertain<F>);
        }

        $crate::__qty_fmt!($Q, $U, $base: Display, LowerExp, UpperExp);

        impl ::core::fmt::Display for $U {
            fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {
                f.pad(self.abbreviation())
            }
        }

        $crate::__qty_if_approx! {
            impl<T: $crate::__private::approx::AbsDiffEq> $crate::__private::approx::AbsDiffEq for $Q<T> {
                type Epsilon = T::Epsilon;
                #[inline]
                fn default_epsilon() -> T::Epsilon {
                    T::default_epsilon()
                }
                #[inline]
                fn abs_diff_eq(&self, other: &Self, epsilon: T::Epsilon) -> bool {
                    self.0.abs_diff_eq(&other.0, epsilon)
                }
            }
            impl<T: $crate::__private::approx::RelativeEq> $crate::__private::approx::RelativeEq for $Q<T> {
                #[inline]
                fn default_max_relative() -> T::Epsilon {
                    T::default_max_relative()
                }
                #[inline]
                fn relative_eq(&self, other: &Self, epsilon: T::Epsilon, max_relative: T::Epsilon) -> bool {
                    self.0.relative_eq(&other.0, epsilon, max_relative)
                }
            }
            impl<T: $crate::__private::approx::UlpsEq> $crate::__private::approx::UlpsEq for $Q<T> {
                #[inline]
                fn default_max_ulps() -> u32 {
                    T::default_max_ulps()
                }
                #[inline]
                fn ulps_eq(&self, other: &Self, epsilon: T::Epsilon, max_ulps: u32) -> bool {
                    self.0.ulps_eq(&other.0, epsilon, max_ulps)
                }
            }
        }

        $crate::__qty_if_bytemuck! {
            // SAFETY: `#[repr(transparent)]` over `T`.
            unsafe impl<T: $crate::__private::bytemuck::Zeroable> $crate::__private::bytemuck::Zeroable for $Q<T> {}
            // SAFETY: as above; `Pod` requires `T: Pod`.
            unsafe impl<T: $crate::__private::bytemuck::Pod> $crate::__private::bytemuck::Pod for $Q<T> {}
            // SAFETY: as above.
            unsafe impl<T> $crate::__private::bytemuck::TransparentWrapper<T> for $Q<T> {}
        }

        impl $crate::UnitEnum for $U {
            const ALL: &'static [Self] = $U::ALL;
        }
        impl $crate::Unit for $U {
            #[inline(always)]
            fn abbreviation(self) -> &'static str {
                $U::abbreviation(self)
            }
            #[inline(always)]
            fn info(self) -> &'static $crate::UnitInfo {
                $U::info(self)
            }
        }

        impl<T: $crate::Number> $Q<T> {
            /// The value in `unit`, for display: `length.in_unit(LengthUnit::Kilometer)`
            /// prints as `1.5 km`.
            #[inline]
            pub fn in_unit<V: $crate::UnitOf<Self>>(self, unit: V) -> $crate::InUnit<T, V> {
                $crate::InUnit {
                    value: self.convert_to(unit),
                    unit,
                }
            }

            /// A quantity from `value` in `unit`. The unit can be a built-in one
            /// like `LengthUnit::Kilometer` or one made with
            /// [`custom_unit!`](qty::custom_unit).
            #[inline]
            pub fn new<V: $crate::UnitOf<Self>>(value: T, unit: V) -> Self {
                Self(unit.value_to_base(value))
            }

            /// The value in `unit`.
            #[inline]
            pub fn convert_to<V: $crate::UnitOf<Self>>(self, unit: V) -> T {
                unit.value_from_base(self.0)
            }
        }

        impl<T: $crate::Float> $Q<T> {
            /// Like `auto_unit`, but choosing from `units`: the largest one
            /// that doesn't exceed the value, or the smallest one if they all
            /// do. For example `length.auto_unit_in(LengthUnit::IMPERIAL)`.
            /// Meant for linear units. An empty list gives the base unit.
            pub fn auto_unit_in(self, units: &[$U]) -> $crate::InUnit<T, $U> {
                $crate::__private::auto_unit_in(self, units)
            }
        }

        $crate::__qty_if_math! {
            impl<T: $crate::FloatMath> $Q<T> {
                /// Rounds to a whole number of `unit`, ties away from zero.
                /// 1.26 m becomes 126 cm, and 21.6 °C becomes 22 °C.
                #[inline]
                pub fn round_in(self, unit: $U) -> Self {
                    Self::new(self.convert_to(unit).round(), unit)
                }

                /// Rounds down to a whole number of `unit`.
                #[inline]
                pub fn floor_in(self, unit: $U) -> Self {
                    Self::new(self.convert_to(unit).floor(), unit)
                }

                /// Rounds up to a whole number of `unit`.
                #[inline]
                pub fn ceil_in(self, unit: $U) -> Self {
                    Self::new(self.convert_to(unit).ceil(), unit)
                }
            }
        }

        /// Parses a number and a unit. The unit can be an abbreviation
        /// (`"1.5 km"`), a name (`"1.5 kilometres"`) or, except for points,
        /// a [unit expression](qty::UnitExpr) with the same dimensions
        /// (`"1.5 km/s*s"`).
        impl<T: $crate::Float + ::core::str::FromStr> ::core::str::FromStr for $Q<T> {
            type Err = $crate::ParseError;
            fn from_str(s: &str) -> ::core::result::Result<Self, $crate::ParseError> {
                $crate::__private::parse_quantity(s, $crate::__private::Exprs::$exprs)
            }
        }
    };
}

/// For built-in quantities: [`__qty_common!`] plus what only they have
/// (`Fixed`, defmt, schemars).
macro_rules! quantity_core {
    ($Q:ident, $U:ident, $base:ident, exprs: $exprs:ident, si: $si:expr) => {
        $crate::__qty_common!($Q, $U, $base, exprs: $exprs, si: $si);

        impl<I: $crate::Integer> $Q<I> {
            /// Rounds a float quantity to a whole number of base units.
            /// For other units, see [`Fixed`](crate::Fixed).
            #[inline]
            pub fn round_from<F: $crate::Float>(
                quantity: $Q<F>,
                mode: $crate::Rounding,
            ) -> Result<Self, $crate::RoundError> {
                $crate::Fixed::<<$Q<f64> as $crate::HasFixedBase>::Base, I>::round_from(quantity, mode)
                    .map(Self::from)
            }
        }

        #[cfg(feature = "defmt")]
        impl<T: defmt::Format> defmt::Format for $Q<T> {
            fn format(&self, f: defmt::Formatter<'_>) {
                defmt::write!(f, "{} {=str}", self.0, $U::$base.abbreviation());
            }
        }

        // What `#[derive]` with `#[serde(transparent)]` would write, through
        // shared visitors (see `serde_impl`).
        #[cfg(feature = "serde")]
        const _: () = {
            const NAMES: [&str; $U::ALL.len()] = $crate::serde_impl::variant_names($U::QUANTITY.units);

            impl<T: serde::Serialize> serde::Serialize for $Q<T> {
                #[inline]
                fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                    self.0.serialize(serializer)
                }
            }
            impl<'de, T: serde::Deserialize<'de>> serde::Deserialize<'de> for $Q<T> {
                #[inline]
                fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                    T::deserialize(deserializer).map(Self)
                }
            }
            impl serde::Serialize for $U {
                #[inline]
                fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                    $crate::serde_impl::serialize_unit(serializer, stringify!($U), *self as usize, &NAMES)
                }
            }
            impl<'de> serde::Deserialize<'de> for $U {
                #[inline]
                fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                    $crate::serde_impl::deserialize_unit(deserializer, stringify!($U), &NAMES, $U::ALL)
                }
            }
        };

        #[cfg(feature = "schemars")]
        impl<T: schemars::JsonSchema> schemars::JsonSchema for $Q<T> {
            fn inline_schema() -> bool {
                true
            }
            fn schema_name() -> std::borrow::Cow<'static, str> {
                $crate::schema::quantity_schema_name::<T>(stringify!($Q))
            }
            /// The storage type's schema (a number for floats), described
            /// with the base unit.
            fn json_schema(generator: &mut schemars::SchemaGenerator) -> schemars::Schema {
                $crate::schema::quantity_schema::<T>(generator, stringify!($Q), $U::$base.info())
            }
        }
        #[cfg(feature = "schemars")]
        impl schemars::JsonSchema for $U {
            fn schema_name() -> std::borrow::Cow<'static, str> {
                stringify!($U).into()
            }
            /// The variant names, as serde writes them.
            fn json_schema(_: &mut schemars::SchemaGenerator) -> schemars::Schema {
                $crate::schema::unit_schema($U::QUANTITY.units)
            }
        }

        #[cfg(feature = "defmt")]
        impl defmt::Format for $U {
            fn format(&self, f: defmt::Formatter<'_>) {
                defmt::write!(f, "{=str}", self.abbreviation());
            }
        }
    };
}

/// Arithmetic for amounts: quantities that can be added, negated and
/// scaled, like lengths, durations and temperature differences.
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_vector_ops {
    ($Q:ident) => {
        impl<I: $crate::Integer> $Q<I> {
            /// `self + other`, or `None` on overflow.
            #[inline]
            pub fn checked_add(self, other: Self) -> ::core::option::Option<Self> {
                self.0.checked_add(other.0).map(Self)
            }

            /// `self - other`, or `None` on overflow.
            #[inline]
            pub fn checked_sub(self, other: Self) -> ::core::option::Option<Self> {
                self.0.checked_sub(other.0).map(Self)
            }
        }

        impl<T: $crate::Float> $Q<T> {
            /// `1` for positive values and `+0`, `-1` for negative values
            /// and `-0`, NaN for NaN (like [`f64::signum`]).
            #[inline]
            pub fn signum(self) -> T {
                if self.0.is_nan() {
                    self.0
                } else if self.0.is_sign_negative() {
                    T::from_f64(-1.0)
                } else {
                    T::from_f64(1.0)
                }
            }

            /// The magnitude of `self` with the sign of `sign` (like
            /// [`f64::copysign`]).
            #[inline]
            pub fn copysign(self, sign: Self) -> Self {
                if self.0.is_sign_negative() == sign.0.is_sign_negative() {
                    self
                } else {
                    Self(-self.0)
                }
            }
        }

        impl $Q<f64> {
            /// Zero. Only for `f64` storage, since a second constant would
            /// make `Length::ZERO` ambiguous. Other storage types have
            /// `default()`.
            pub const ZERO: Self = Self(0.0);
        }

        $crate::__qty_if_math! {
            impl<T: $crate::FloatMath> $Q<T> {
                /// `sqrt(self² + other²)`: the magnitude of two perpendicular
                /// components, without intermediate overflow.
                #[inline]
                pub fn hypot(self, other: Self) -> Self {
                    Self(self.0.hypot(other.0))
                }
            }
        }

        impl<T: ::core::ops::Add<Output = T>> ::core::ops::Add for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn add(self, rhs: Self) -> Self {
                Self(self.0 + rhs.0)
            }
        }
        impl<T: ::core::ops::Sub<Output = T>> ::core::ops::Sub for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn sub(self, rhs: Self) -> Self {
                Self(self.0 - rhs.0)
            }
        }
        impl<T: ::core::ops::Neg<Output = T>> ::core::ops::Neg for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn neg(self) -> Self {
                Self(-self.0)
            }
        }
        impl<T: ::core::ops::Rem<Output = T>> ::core::ops::Rem for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn rem(self, rhs: Self) -> Self {
                Self(self.0 % rhs.0)
            }
        }
        impl<T: ::core::ops::AddAssign> ::core::ops::AddAssign for $Q<T> {
            #[inline(always)]
            fn add_assign(&mut self, rhs: Self) {
                self.0 += rhs.0;
            }
        }
        impl<T: ::core::ops::SubAssign> ::core::ops::SubAssign for $Q<T> {
            #[inline(always)]
            fn sub_assign(&mut self, rhs: Self) {
                self.0 -= rhs.0;
            }
        }
        impl<T: ::core::ops::RemAssign> ::core::ops::RemAssign for $Q<T> {
            #[inline(always)]
            fn rem_assign(&mut self, rhs: Self) {
                self.0 %= rhs.0;
            }
        }

        impl<T: ::core::ops::MulAssign> ::core::ops::MulAssign<T> for $Q<T> {
            #[inline(always)]
            fn mul_assign(&mut self, rhs: T) {
                self.0 *= rhs;
            }
        }
        impl<T: ::core::ops::DivAssign> ::core::ops::DivAssign<T> for $Q<T> {
            #[inline(always)]
            fn div_assign(&mut self, rhs: T) {
                self.0 /= rhs;
            }
        }
        $crate::__qty_scalar_lhs_mul!($Q: f64, i8, i16, i32, i64, i128, isize, u8, u16, u32, u64, u128, usize);

        // Uses `T`'s own `Sum`, so this behaves and compiles like summing
        // the numbers.
        impl<T: ::core::iter::Sum> ::core::iter::Sum for $Q<T> {
            #[inline]
            fn sum<I: Iterator<Item = Self>>(iter: I) -> Self {
                Self(iter.map(|q| q.0).sum())
            }
        }
        impl<'a, T: ::core::iter::Sum<&'a T> + 'a> ::core::iter::Sum<&'a $Q<T>> for $Q<T> {
            #[inline]
            fn sum<I: Iterator<Item = &'a Self>>(iter: I) -> Self {
                Self(iter.map(|q| &q.0).sum())
            }
        }
    };
}

/// `quantity * number`, `quantity / number` and `quantity / quantity` for
/// quantities without the generic operators of [`arith`](crate::arith).
#[doc(hidden)]
#[macro_export]
macro_rules! __qty_scalar_ops {
    ($Q:ident) => {
        $crate::__qty_scalar_ops!(@ratio $Q);
        impl<T: ::core::ops::Mul<Output = T>> ::core::ops::Mul<T> for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn mul(self, rhs: T) -> Self {
                Self(self.0 * rhs)
            }
        }
        impl<T: ::core::ops::Div<Output = T>> ::core::ops::Div<T> for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn div(self, rhs: T) -> Self {
                Self(self.0 / rhs)
            }
        }
    };
    (@ratio $Q:ident) => {
        /// Dividing two values of the same quantity gives a plain number.
        impl<T: ::core::ops::Div<Output = T>> ::core::ops::Div for $Q<T> {
            type Output = T;
            #[inline(always)]
            fn div(self, rhs: Self) -> T {
                self.0 / rhs.0
            }
        }
    };
}

/// Everything an amount quantity needs apart from its unit conversions.
macro_rules! quantity {
    (arith $Q:ident, $U:ident, $base:ident, si: $si:expr) => {
        quantity_core!($Q, $U, $base, exprs: Base, si: $si);
        $crate::__qty_vector_ops!($Q);
    };
    ($Q:ident, $U:ident, $base:ident, si: $si:expr) => {
        quantity_core!($Q, $U, $base, exprs: Base, si: $si);
        $crate::__qty_vector_ops!($Q);
        $crate::__qty_scalar_ops!($Q);
    };
}

/// A point on a scale rather than an amount, such as an absolute
/// temperature. Points can't be added, negated or scaled (20 °C + 20 °C
/// isn't 40 °C). Their differences are amounts of `$D`:
///
/// * `point - point = $D`
/// * `point ± $D = point`, `$D + point = point`, `point ±= $D`
///
/// `point / point` is still allowed, as a ratio of absolute values.
macro_rules! point_quantity {
    ($Q:ident, $U:ident, $base:ident, $D:ident, si: $si:expr) => {
        quantity_core!($Q, $U, $base, exprs: Off, si: $si);
        $crate::__qty_scalar_ops!(@ratio $Q);

        impl<T: core::ops::Sub<Output = T>> core::ops::Sub for $Q<T> {
            type Output = $D<T>;
            #[inline(always)]
            fn sub(self, rhs: Self) -> $D<T> {
                $D::from_base(self.0 - rhs.0)
            }
        }
        impl<T: core::ops::Add<Output = T>> core::ops::Add<$D<T>> for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn add(self, rhs: $D<T>) -> Self {
                Self(self.0 + rhs.into_base())
            }
        }
        impl<T: core::ops::Add<Output = T>> core::ops::Add<$Q<T>> for $D<T> {
            type Output = $Q<T>;
            #[inline(always)]
            fn add(self, rhs: $Q<T>) -> $Q<T> {
                $Q::from_base(self.into_base() + rhs.0)
            }
        }
        impl<T: core::ops::Sub<Output = T>> core::ops::Sub<$D<T>> for $Q<T> {
            type Output = Self;
            #[inline(always)]
            fn sub(self, rhs: $D<T>) -> Self {
                Self(self.0 - rhs.into_base())
            }
        }
        impl<T: core::ops::AddAssign> core::ops::AddAssign<$D<T>> for $Q<T> {
            #[inline(always)]
            fn add_assign(&mut self, rhs: $D<T>) {
                self.0 += rhs.into_base();
            }
        }
        impl<T: core::ops::SubAssign> core::ops::SubAssign<$D<T>> for $Q<T> {
            #[inline(always)]
            fn sub_assign(&mut self, rhs: $D<T>) {
                self.0 -= rhs.into_base();
            }
        }
    };
}

/// `A * B = C` (and `B * A = C` when emitted separately), computed in base
/// units. `$k` is the factor relating the base units, `1` for coherent SI.
#[allow(unused_macros)] // only for quantities without the generic operators
macro_rules! cross_mul {
    ($A:ident * $B:ident = $C:ident) => {
        impl<T: core::ops::Mul<Output = T>> core::ops::Mul<$B<T>> for $A<T> {
            type Output = $C<T>;
            #[inline(always)]
            fn mul(self, rhs: $B<T>) -> $C<T> {
                $C::from_base(self.into_base() * rhs.into_base())
            }
        }
    };
    ($A:ident * $B:ident = $C:ident; $k:literal) => {
        impl<T: $crate::Number> core::ops::Mul<$B<T>> for $A<T> {
            type Output = $C<T>;
            #[inline(always)]
            fn mul(self, rhs: $B<T>) -> $C<T> {
                $C::from_base(self.into_base() * rhs.into_base() * T::from_f64($k))
            }
        }
    };
}

/// `A / B = C`, computed in base units.
#[allow(unused_macros)] // only for quantities without the generic operators
macro_rules! cross_div {
    ($A:ident / $B:ident = $C:ident) => {
        impl<T: core::ops::Div<Output = T>> core::ops::Div<$B<T>> for $A<T> {
            type Output = $C<T>;
            #[inline(always)]
            fn div(self, rhs: $B<T>) -> $C<T> {
                $C::from_base(self.into_base() / rhs.into_base())
            }
        }
    };
    ($A:ident / $B:ident = $C:ident; $k:literal) => {
        impl<T: $crate::Number> core::ops::Div<$B<T>> for $A<T> {
            type Output = $C<T>;
            #[inline(always)]
            #[allow(clippy::suspicious_arithmetic_impl)]
            fn div(self, rhs: $B<T>) -> $C<T> {
                $C::from_base(self.into_base() / rhs.into_base() * T::from_f64($k))
            }
        }
    };
}

/// `A * B` is dimensionless: the result is a plain number. Unused while
/// all such products are between quantities with the generic operators.
#[allow(unused_macros)]
macro_rules! cross_mul_scalar {
    ($A:ident * $B:ident) => {
        impl<T: core::ops::Mul<Output = T>> core::ops::Mul<$B<T>> for $A<T> {
            type Output = T;
            #[inline(always)]
            fn mul(self, rhs: $B<T>) -> T {
                self.into_base() * rhs.into_base()
            }
        }
    };
}

/// `C.sqrt() = A` where `C = A * A`, such as `Area` to `Length`. `$k`
/// relates the base units when they aren't coherent.
macro_rules! cross_sqrt {
    ($C:ident => $A:ident) => {
        cross_sqrt!(@impl $C => $A, sqrt, "square", |v| v);
        cross_power!($A => $C, squared, "square", |a| a * a);
    };
    ($C:ident => $A:ident; $k:literal) => {
        cross_sqrt!(@impl $C => $A, sqrt, "square", |v| v / T::from_f64($k));
        cross_power!($A => $C, squared, "square", |a| a * a * T::from_f64($k));
    };
    (@impl $C:ident => $A:ident, $method:ident, $what:literal, |$v:ident| $scaled:expr) => {
        #[cfg(any(feature = "std", feature = "libm"))]
        impl<T: $crate::FloatMath> $C<T> {
            #[doc = concat!(
                "The [`", stringify!($A), "`] whose ", $what, " is this [`",
                stringify!($C), "`]."
            )]
            #[inline]
            pub fn $method(self) -> $A<T> {
                let $v = self.into_base();
                $A::from_base(($scaled).$method())
            }
        }
    };
}

/// `A.squared() = C` and `A.cubed() = C`: the inverses of `cross_sqrt!` and
/// `cross_cbrt!`; `$k` as there.
macro_rules! cross_power {
    ($A:ident => $C:ident, $method:ident, $what:literal, |$v:ident| $value:expr) => {
        impl<T: $crate::Number + Copy> $A<T> {
            #[doc = concat!("The ", $what, " of this quantity: a [`", stringify!($C), "`].")]
            #[inline]
            pub fn $method(self) -> $C<T> {
                let $v = self.into_base();
                $C::from_base($value)
            }
        }
    };
}

/// `C.cbrt() = A` where `C = A * A * A`, such as `Volume` to `Length`.
macro_rules! cross_cbrt {
    ($C:ident => $A:ident) => {
        cross_sqrt!(@impl $C => $A, cbrt, "cube", |v| v);
        cross_power!($A => $C, cubed, "cube", |a| a * a * a);
    };
    ($C:ident => $A:ident; $k:literal) => {
        cross_sqrt!(@impl $C => $A, cbrt, "cube", |v| v / T::from_f64($k));
        cross_power!($A => $C, cubed, "cube", |a| a * a * a * T::from_f64($k));
    };
}

/// `1 / A = B` for `f64` storage: `1.0 / duration` is a `Frequency`. Not
/// for `f32`, for the reason given on `__qty_scalar_lhs_mul!`.
macro_rules! cross_recip {
    ($A:ident => $B:ident) => {
        impl core::ops::Div<$A<f64>> for f64 {
            type Output = $B<f64>;
            #[inline(always)]
            fn div(self, rhs: $A<f64>) -> $B<f64> {
                $B::from_base(self / rhs.into_base())
            }
        }
    };
}

/// Declares the [`FixedUnit`] marker for one unit. `$from` and `$as` name
/// the unit's conversion methods; the marker doesn't call them, as the
/// provided `to_quantity` and `from_quantity` reach the same code via `UNIT`.
macro_rules! fixed_unit {
    // Units of ordinary quantities: counts can be added.
    ($M:ident: $Q:ident, $U:ident :: $V:ident, base $B:ident,
     $num:literal / $den:literal, pi^$pi:literal, $from:ident, $as:ident, additive) => {
        fixed_unit!($M: $Q, $U::$V, base $B, $num / $den, pi^$pi, $from, $as);
        impl $crate::AdditiveUnit for $M {}
    };
    // Units of point quantities: differences are counts of `$delta`.
    ($M:ident: $Q:ident, $U:ident :: $V:ident, base $B:ident,
     $num:literal / $den:literal, pi^$pi:literal, $from:ident, $as:ident
     $(, offset($on:expr, $od:expr))?, point $delta:path) => {
        fixed_unit!($M: $Q, $U::$V, base $B, $num / $den, pi^$pi, $from, $as $(, offset($on, $od))?);

        impl $crate::PointUnit for $M {
            type Delta = $delta;
        }
        /// `point - point` is a difference, in the delta unit of the same scale.
        impl<V: $crate::PointUnit<Unit = super::$U>, I: $crate::Integer>
            core::ops::Sub<$crate::Fixed<V, I>> for $crate::Fixed<$M, I>
        {
            type Output = $crate::Fixed<$delta, I>;
            #[inline(always)]
            fn sub(self, rhs: $crate::Fixed<V, I>) -> Self::Output {
                $crate::Fixed::new(self.count() - rhs.count_in::<$M>())
            }
        }
        impl<D: $crate::AdditiveUnit<Unit = <$delta as $crate::FixedUnit>::Unit>, I: $crate::Integer>
            core::ops::Add<$crate::Fixed<D, I>> for $crate::Fixed<$M, I>
        {
            type Output = Self;
            #[inline(always)]
            fn add(self, rhs: $crate::Fixed<D, I>) -> Self {
                $crate::Fixed::new(self.count() + rhs.count_in::<$delta>())
            }
        }
        impl<D: $crate::AdditiveUnit<Unit = <$delta as $crate::FixedUnit>::Unit>, I: $crate::Integer>
            core::ops::AddAssign<$crate::Fixed<D, I>> for $crate::Fixed<$M, I>
        {
            #[inline(always)]
            fn add_assign(&mut self, rhs: $crate::Fixed<D, I>) {
                *self = *self + rhs;
            }
        }
        impl<D: $crate::AdditiveUnit<Unit = <$delta as $crate::FixedUnit>::Unit>, I: $crate::Integer>
            core::ops::SubAssign<$crate::Fixed<D, I>> for $crate::Fixed<$M, I>
        {
            #[inline(always)]
            fn sub_assign(&mut self, rhs: $crate::Fixed<D, I>) {
                *self = self.sub_delta(rhs);
            }
        }
    };
    ($M:ident: $Q:ident, $U:ident :: $V:ident, base $B:ident,
     $num:literal / $den:literal, pi^$pi:literal, $from:ident, $as:ident
     $(, offset($on:expr, $od:expr))?) => {
        #[doc = concat!(
            "Marker for counting [`", stringify!($Q), "`](super::", stringify!($Q),
            ") in [`", stringify!($V), "`](super::", stringify!($U), "::", stringify!($V),
            ") with [`Fixed`](crate::Fixed)."
        )]
        // Markers are only type parameters and unit arguments: `Debug`
        // on 1,700 of them would cost a tenth of the crate's build time.
        #[derive(Clone, Copy)]
        #[allow(missing_debug_implementations)]
        pub struct $M;

        impl $crate::FixedUnit for $M {
            type Quantity<F: $crate::Float> = super::$Q<F>;
            type Unit = super::$U;
            type Base = $B;
            const UNIT: super::$U = super::$U::$V;
            const NUM: u128 = $num;
            const DEN: u128 = $den;
            const PI_POW: i32 = $pi;
            $(
                const OFFSET_NUM: i128 = $on;
                const OFFSET_DEN: u128 = $od;
            )?
        }
    };
}

/// The relation between three quantities' unit enums, for `Fixed::mul_to`
/// and `Fixed::div_to`.
macro_rules! fixed_relation {
    ($Tr:ident: $A:ident, $B:ident => $C:ident; $num:literal / $den:literal, pi^$pi:literal) => {
        impl $crate::$Tr<$B> for $A {
            type Output = $C;
            const K: (u128, u128, i32) = ($num, $den, $pi);
        }
    };
}

/// Links a quantity with its base-unit marker: `Length<I>` and
/// `Fixed<Meter, I>` are the same thing and convert freely.
macro_rules! fixed_base {
    ($Q:ident, $B:ident) => {
        impl<T> $crate::HasFixedBase for $Q<T> {
            type Base = unit::$B;
        }
        impl<I> From<$Q<I>> for $crate::Fixed<unit::$B, I> {
            #[inline(always)]
            fn from(q: $Q<I>) -> Self {
                $crate::Fixed::new(q.into_base())
            }
        }
        impl<I: Copy> From<$crate::Fixed<unit::$B, I>> for $Q<I> {
            #[inline(always)]
            fn from(f: $crate::Fixed<unit::$B, I>) -> Self {
                $Q::from_base(f.count())
            }
        }
    };
}

/// Maps a quantity type to the [`FixedUnit`] marker of its base unit.
#[doc(hidden)]
pub trait HasFixedBase {
    type Base: FixedUnit;
}

